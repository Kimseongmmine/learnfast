-- 001_users.sql — 사용자 테이블
--
-- 마이그레이션(migration) 이란: DB 구조를 바꾼 기록을 순서대로 쌓아둔 파일 묶음이다.
-- 번호를 앞에 붙이는 이유는 순서가 곧 의미이기 때문이다 - 002 는 001 이 만든 테이블을
-- 전제로 하고, 순서가 바뀌면 실행되지 않는다.
--
-- 이 파일이 있어야 하는 이유:
--   1. 저장소를 받은 사람이 DB 를 똑같이 만들 수 있다
--   2. "언제 뭘 왜 바꿨는지" 가 git 기록에 남는다
--   3. DB 를 새로 만들 일이 생겼을 때 기억에 의존하지 않는다
--
-- 실행: Supabase → SQL Editor 에 붙여넣고 Run.
-- (도구로 자동 실행하는 건 나중 이야기다. 지금은 파일 두 개뿐이라 손으로 하는 게 더 명확하다.)

create table if not exists users (
  -- 줄이 생길 때마다 1, 2, 3... 자동으로 번호를 매긴다.
  -- 이 번호가 JWT 안에 들어가는 값이다.
  id            bigserial primary key,

  -- unique 가 핵심이다. 같은 이메일로 두 번 가입하는 걸 DB 가 직접 막는다.
  -- 코드에서 "먼저 조회해보고 없으면 넣기" 로 하면, 두 요청이 동시에 들어왔을 때
  -- 둘 다 "없음" 을 보고 둘 다 넣으려 드는 틈이 생긴다. DB 제약에는 그 틈이 없다.
  email         text unique not null,

  -- 이름을 password 로 짓지 않는다. 원문을 넣으면 안 된다는 걸 컬럼 이름이 말하게 한다.
  -- bcrypt 결과는 알고리즘·코스트·솔트·해시가 한 덩어리라 컬럼 하나면 된다(60자).
  password_hash text not null,

  -- timestamptz = 시간대까지 함께 저장. 서버가 어느 지역에 있든 어긋나지 않는다.
  created_at    timestamptz not null default now()
);
